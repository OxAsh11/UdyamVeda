// Validates supabase/seed/mvp/questions.json against the fact dictionary and
// writes an idempotent SQL migration that replaces the questions.
//
//   node scripts/mvp-questions-sql.mjs supabase/migrations/<timestamp>_questions_seed.sql
//
// Applied migrations are never edited: after changing the JSON, generate a
// new migration file with a new timestamp.
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const read = name => JSON.parse(fs.readFileSync(path.join(root, 'supabase/seed/mvp', name), 'utf8'))
const questions = read('questions.json')
const factKeys = new Set(read('facts.json').facts.map(fact => fact.key))
const KINDS = new Set(['single', 'multi', 'number', 'band', 'yes_no', 'date', 'text', 'activity_search'])

const errors = []
const seen = new Set()
for (const question of questions) {
  const label = `question ${question.id}`
  if (!/^[a-z][a-z0-9_]*$/.test(question.id ?? '')) errors.push(`${label}: bad id`)
  if (seen.has(question.id)) errors.push(`${label}: duplicate`)
  seen.add(question.id)
  if (!KINDS.has(question.kind)) errors.push(`${label}: bad kind ${question.kind}`)
  if (!(question.stage >= 1 && question.stage <= 9)) errors.push(`${label}: bad stage`)
  for (const lang of ['en', 'hi', 'mr']) if (!question[lang]?.trim()) errors.push(`${label}: no ${lang} prompt`)
  if (!question.facts?.length) errors.push(`${label}: writes no fact`)
  for (const key of question.facts ?? []) if (!factKeys.has(key)) errors.push(`${label}: unknown fact ${key}`)
}
if (errors.length) {
  console.error(`Questions have ${errors.length} problem(s):\n- ${errors.join('\n- ')}`)
  process.exit(1)
}

const q = value => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`)
const ids = questions.map(question => q(question.id)).join(', ')

const sql = [
  '-- Generated by scripts/mvp-questions-sql.mjs from supabase/seed/mvp/questions.json. Do not edit by hand.',
  `-- ${questions.length} questions.`,
  '',
  `delete from public.question_facts where question_id in (${ids});`,
  `delete from public.questions where id not in (${ids});`,
  '',
  'insert into public.questions (id, ask_stage, sort_order, answer_kind, prompt_en, prompt_hi, prompt_mr, help_en, help_hi, help_mr, depends_on) values',
  questions.map(question => `  (${[
    q(question.id), question.stage, question.sort, q(question.kind), q(question.en), q(question.hi), q(question.mr),
    q(question.help_en), q(question.help_hi), q(question.help_mr),
    question.depends_on ? `${q(JSON.stringify(question.depends_on))}::jsonb` : 'null',
  ].join(', ')})`).join(',\n'),
  'on conflict (id) do update set ask_stage = excluded.ask_stage, sort_order = excluded.sort_order, answer_kind = excluded.answer_kind, prompt_en = excluded.prompt_en, prompt_hi = excluded.prompt_hi, prompt_mr = excluded.prompt_mr, help_en = excluded.help_en, help_hi = excluded.help_hi, help_mr = excluded.help_mr, depends_on = excluded.depends_on;',
  '',
  'insert into public.question_facts (question_id, fact_key) values',
  questions.flatMap(question => question.facts.map(key => `  (${q(question.id)}, ${q(key)})`)).join(',\n') + ';',
  '',
].join('\n')

fs.writeFileSync(path.resolve(process.argv[2]), sql)
console.log(`Wrote ${process.argv[2]}: ${questions.length} questions.`)
