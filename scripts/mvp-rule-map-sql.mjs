// Validates supabase/seed/mvp/rule-field-map.json against the fact dictionary
// (facts.json) and the derivations in src/lib/opportunities/fact-mapping.ts,
// then writes an idempotent SQL migration that upserts rule_field_mappings.
//
//   node scripts/mvp-rule-map-sql.mjs supabase/migrations/<timestamp>_rule_field_mappings_seed.sql
//
// Applied migrations are never edited: after changing the JSON, generate a
// new migration file with a new timestamp.
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const rows = JSON.parse(fs.readFileSync(path.join(root, 'supabase/seed/mvp/rule-field-map.json'), 'utf8'))
const factKeys = new Set(JSON.parse(fs.readFileSync(path.join(root, 'supabase/seed/mvp/facts.json'), 'utf8')).facts.map(f => f.key))
const mappingSource = fs.readFileSync(path.join(root, 'src/lib/opportunities/fact-mapping.ts'), 'utf8')
const derivationBlock = mappingSource.slice(mappingSource.indexOf('export const DERIVATIONS'), mappingSource.indexOf('/** Facts keyed by legacy rule field'))
const derivations = new Set([...derivationBlock.matchAll(/^ {2}([a-z][a-z0-9_]*):/gm)].map(m => m[1]))

const errors = []
const seen = new Set()
for (const row of rows) {
  const label = `mapping ${row.legacy_field}`
  if (!/^[a-z][a-z0-9_]*$/.test(row.legacy_field ?? '')) errors.push(`${label}: bad field name`)
  if (seen.has(row.legacy_field)) errors.push(`${label}: duplicate`)
  seen.add(row.legacy_field)
  if (row.treatment === 'fact') {
    if (!factKeys.has(row.fact_key)) errors.push(`${label}: unknown fact ${row.fact_key}`)
  } else if (row.treatment === 'derived') {
    if (!derivations.has(row.derive)) errors.push(`${label}: unknown derivation ${row.derive}`)
  } else if (row.treatment === 'bank_check') {
    if (!row.check_note_en?.trim()) errors.push(`${label}: bank check needs a note`)
  } else {
    errors.push(`${label}: bad treatment ${row.treatment}`)
  }
}
if (errors.length) {
  console.error(`Rule map has ${errors.length} problem(s):\n- ${errors.join('\n- ')}`)
  process.exit(1)
}

const q = value => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`)
const count = t => rows.filter(r => r.treatment === t).length
const sql = [
  '-- Generated by scripts/mvp-rule-map-sql.mjs from supabase/seed/mvp/rule-field-map.json. Do not edit by hand.',
  `-- ${rows.length} rule fields: ${count('fact')} fact, ${count('derived')} derived, ${count('bank_check')} bank_check.`,
  '',
  'insert into public.rule_field_mappings (legacy_field, treatment, fact_key, value_map, derive, check_note_en) values',
  rows.map(r => `  (${q(r.legacy_field)}, ${q(r.treatment)}, ${q(r.fact_key ?? null)}, ${r.value_map ? `${q(JSON.stringify(r.value_map))}::jsonb` : 'null'}, ${q(r.derive ?? null)}, ${q(r.check_note_en ?? null)})`).join(',\n'),
  'on conflict (legacy_field) do update set treatment = excluded.treatment, fact_key = excluded.fact_key, value_map = excluded.value_map, derive = excluded.derive, check_note_en = excluded.check_note_en;',
  '',
].join('\n')

const out = process.argv[2]
if (out) {
  fs.writeFileSync(path.resolve(out), sql)
  console.log(`Wrote ${out}: ${rows.length} mappings.`)
} else {
  console.log(`Valid: ${rows.length} mappings (${derivations.size} derivations available). Pass an output path to write SQL.`)
}
