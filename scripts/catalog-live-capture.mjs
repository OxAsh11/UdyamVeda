import fs from 'node:fs'
import path from 'node:path'
import os from 'node:os'
import { execFile } from 'node:child_process'
import { createHash } from 'node:crypto'
import { promisify } from 'node:util'

const root = process.cwd()
const manifestPath = path.join(root, 'docs', 'catalog-review-batches.json')
const outputPath = path.join(root, 'docs', 'catalog-live-source-capture.json')
const snapshotRoot = path.join(root, '.catalog-snapshots')
const execFileAsync = promisify(execFile)

function readEnv(name) {
  if (process.env[name]) return process.env[name]
  const envPath = path.join(root, '.env.local')
  if (!fs.existsSync(envPath)) return null
  const line = fs.readFileSync(envPath, 'utf8')
    .split(/\r?\n/)
    .find(value => new RegExp(`^\\s*${name.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&')}\\s*=`).test(value))
  return line?.split('=', 2)[1]?.trim().replace(/^['"]|['"]$/g, '') ?? null
}

function argumentValue(name, fallback) {
  const index = process.argv.indexOf(name)
  const value = index >= 0 ? Number(process.argv[index + 1]) : fallback
  return Number.isInteger(value) && value > 0 ? value : fallback
}

function nonNegativeArgumentValue(name, fallback) {
  const index = process.argv.indexOf(name)
  const value = index >= 0 ? Number(process.argv[index + 1]) : fallback
  return Number.isInteger(value) && value >= 0 ? value : fallback
}

function stringArgumentValue(name) {
  const index = process.argv.indexOf(name)
  const value = index >= 0 ? process.argv[index + 1] : null
  return typeof value === 'string' && value.trim() ? value.trim() : null
}

function snapshotFileName(slug, contentHash) {
  return `${slug.replace(/[^a-z0-9-]+/gi, '-').replace(/^-|-$/g, '')}-${contentHash.slice(0, 12)}.md`
}

function captureKey(capture) {
  return `${capture.slug}::${capture.sourceUrl}`
}

function isUsableMarkdown(markdown) {
  const normalized = markdown.trim().toLowerCase()
  const urlLike = /^(?:https?:\/\/|\/)\S+$/
  if (normalized.length < 80) return false
  if (urlLike.test(normalized)) return false
  if (/^(?:#\s*)?(?:not found|page not found|\d{3}\s+error)(?:\s|$)/.test(normalized)) return false
  if (normalized.includes('the requested url was not found')) return false
  if (normalized.includes('page not found')) return false
  if (normalized.includes('requested page could not be found')) return false
  if (normalized.includes('requested url was rejected')) return false
  if (normalized.includes('consult with your administrator')) return false
  if (normalized.includes('access denied')) return false
  if (normalized.includes('potentially suspicious content entered by you')) return false
  if (normalized.includes('review all errors and resolve them one by one')) return false
  if (normalized.includes('support id:')) return false
  if (normalized.includes('404 banner')) return false
  if (normalized.includes('request blocked')) return false
  if (normalized.includes("we can't connect to the server at this time")) return false
  if (normalized.includes('generated by cloudfront')) return false
  if (normalized.includes('error code "err_')) return false
  return true
}

function htmlToText(html) {
  const namedEntities = {
    amp: '&',
    apos: "'",
    gt: '>',
    lt: '<',
    nbsp: ' ',
    quot: '"',
  }
  return html
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '')
    .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, '')
    .replace(/<noscript\b[^>]*>[\s\S]*?<\/noscript>/gi, '')
    .replace(/<svg\b[^>]*>[\s\S]*?<\/svg>/gi, '')
    .replace(/<(?:br|\/p|\/div|\/li|\/section|\/article|\/h[1-6])\s*\/?>/gi, '\n')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&(#\d+|#x[\da-f]+|[a-z][\da-z]+);/gi, (_, entity) => {
      if (entity[0] === '#') {
        const hexadecimal = entity[1].toLowerCase() === 'x'
        const value = Number.parseInt(entity.slice(hexadecimal ? 2 : 1), hexadecimal ? 16 : 10)
        return Number.isFinite(value) ? String.fromCodePoint(value) : ' '
      }
      return namedEntities[entity.toLowerCase()] ?? ' '
    })
    .replace(/[ \t]+/g, ' ')
    .replace(/\n\s+/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

function sameHost(sourceUrl, resolvedUrl) {
  const sourceHost = new URL(sourceUrl).hostname.replace(/^www\./i, '').toLowerCase()
  const resolvedHost = new URL(resolvedUrl).hostname.replace(/^www\./i, '').toLowerCase()
  return sourceHost === resolvedHost
}

function isPdfUrl(url) {
  return /.pdf(?:$|[?#])/i.test(new URL(url).pathname)
}

function pdfPythonExecutable() {
  const configured = readEnv('UDYAMVEDA_PYTHON')
  if (configured) return configured
  const bundled = path.join(os.homedir(), '.cache', 'codex-runtimes', 'codex-primary-runtime', 'dependencies', 'python', 'python.exe')
  return fs.existsSync(bundled) ? bundled : (process.platform === 'win32' ? 'python.exe' : 'python3')
}

async function capturePdfFallback(url, timeoutMs) {
  const response = await fetch(url, {
    headers: { Accept: 'application/pdf,application/octet-stream' },
    redirect: 'follow',
    signal: AbortSignal.timeout(timeoutMs + 15000),
  })
  if (!response.ok) throw new Error(`PDF fallback returned ${response.status}`)
  if (!sameHost(url, response.url || url)) throw new Error('PDF fallback redirected to a different host')
  const contentType = response.headers.get('content-type') ?? ''
  if (!/application\/pdf/i.test(contentType) && !(isPdfUrl(url) && /application\/octet-stream/i.test(contentType))) {
    throw new Error(`PDF fallback cannot extract content type ${contentType || 'unknown'}`)
  }
  const bytes = Buffer.from(await response.arrayBuffer())
  const sourceDocumentHash = createHash('sha256').update(bytes).digest('hex')
  const tempDirectory = fs.mkdtempSync(path.join(os.tmpdir(), 'udyamveda-pdf-'))
  const pdfPath = path.join(tempDirectory, 'source.pdf')
  fs.writeFileSync(pdfPath, bytes)
  try {
    const { stdout } = await execFileAsync(pdfPythonExecutable(), [path.join(root, 'scripts', 'extract-pdf-text.py'), pdfPath], {
      maxBuffer: 32 * 1024 * 1024,
      windowsHide: true,
    })
    const extracted = JSON.parse(stdout)
    const pages = Array.isArray(extracted.pages) ? extracted.pages : []
    const markdown = [
      '# Official PDF text extraction',
      '',
      `Source URL: ${url}`,
      `Source document SHA-256: ${sourceDocumentHash}`,
      `Page count: ${pages.length}`,
      '',
      ...pages.flatMap(page => [`## Page ${page.page}`, '', String(page.text ?? '').trim(), '']),
    ].join('\n').trim()
    if (!isUsableMarkdown(markdown)) throw new Error('PDF fallback returned no usable extracted text')
    return { markdown, sourceDocumentHash, pageCount: pages.length, responseContentType: contentType }
  } finally {
    fs.rmSync(tempDirectory, { recursive: true, force: true })
  }
}

async function captureHtmlFallback(url, timeoutMs) {
  const response = await fetch(url, {
    headers: { Accept: 'text/html,application/xhtml+xml' },
    redirect: 'follow',
    signal: AbortSignal.timeout(timeoutMs + 15000),
  })
  if (!response.ok) throw new Error(`HTTP fallback returned ${response.status}`)
  if (!sameHost(url, response.url || url)) throw new Error('HTTP fallback redirected to a different host')
  const contentType = response.headers.get('content-type') ?? ''
  if (!/text\/html|application\/xhtml\+xml/i.test(contentType)) {
    throw new Error(`HTTP fallback cannot extract content type ${contentType || 'unknown'}`)
  }
  const text = htmlToText(await response.text())
  if (!isUsableMarkdown(text)) throw new Error('HTTP fallback returned no usable HTML text')
  return text
}

function needsCaptureRefresh(previous) {
  if (!previous || previous.status === 'failed') return true
  if (previous.status !== 'captured' || !previous.snapshotPath) return true
  const snapshotPath = path.join(root, previous.snapshotPath)
  if (!fs.existsSync(snapshotPath)) return true
  return !isUsableMarkdown(fs.readFileSync(snapshotPath, 'utf8'))
}

function failureMetadata(error) {
  const message = error instanceof Error ? error.message : String(error ?? 'Unknown capture error')
  const retryable = /fetch failed|timeout|timed out|returned (408|425|429|5\d\d)\b|econn|enotfound|eai_again/i.test(message)
  const failureKind = /returned (402|403)\b|insufficient credits|credit quota|quota exhausted/i.test(message)
    ? 'quota_exhausted'
    : /no usable markdown content/i.test(message)
    ? 'unusable_content'
    : retryable
      ? 'transient_fetch'
      : 'source_or_policy'
  return { error: message, failureKind, retryable }
}

function retryDelayMs(attempt) {
  return Math.min(5000, 500 * (2 ** Math.max(0, attempt - 1)))
}

function wait(ms) {
  return new Promise(resolve => setTimeout(resolve, ms))
}

function errorWithAttempts(error, attempts) {
  const message = error instanceof Error ? error.message : String(error ?? 'Unknown capture error')
  const decorated = new Error(message)
  decorated.attempts = attempts
  return decorated
}

const firecrawlKey = readEnv('FIRECRAWL_API_KEY')
const allowHttpFallback = process.argv.includes('--http-fallback')
const httpOnly = process.argv.includes('--http-only')
const pdfOnly = process.argv.includes('--pdf-only')
if (!firecrawlKey && !allowHttpFallback && !httpOnly && !pdfOnly) throw new Error('FIRECRAWL_API_KEY is not configured; pass --http-fallback, --http-only, or --pdf-only for review-blocked source capture')
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
const existingManifest = fs.existsSync(outputPath) ? JSON.parse(fs.readFileSync(outputPath, 'utf8')) : null
const existingCapturesByKey = new Map((existingManifest?.captures ?? []).map(capture => [captureKey(capture), capture]))
const records = manifest.batches.flatMap(batch => batch.records)
const limit = argumentValue('--limit', 1)
const offset = nonNegativeArgumentValue('--offset', 0)
const timeoutMs = Math.min(argumentValue('--timeout-ms', 30000), 120000)
const retries = nonNegativeArgumentValue('--retries', 2)
const maxAttempts = retries + 1
const requestedSlug = stringArgumentValue('--slug')
const candidateRecords = pdfOnly ? records.filter(record => record.source?.url && isPdfUrl(record.source.url)) : records
const resumableRecords = process.argv.includes('--resume')
  ? candidateRecords.filter(record => {
    if (!record.source?.url) return false
    const previous = existingCapturesByKey.get(`${record.slug}::${record.source.url}`)
    return needsCaptureRefresh(previous)
  })
  : candidateRecords.filter(record => record.source?.url)
const filteredRecords = requestedSlug
  ? resumableRecords.filter(record => record.slug === requestedSlug)
  : resumableRecords
const selected = filteredRecords.slice(offset, offset + limit)
const runId = new Date().toISOString().replace(/[:.]/g, '-')
const runDirectory = path.join(snapshotRoot, runId)
const captures = []

for (const record of selected) {
  const startedAt = new Date().toISOString()
  try {
    let markdown = null
    let captureMethod = 'firecrawl_markdown'
    let sourceDocumentHash = null
    let pageCount = null
    let responseContentType = null
    let attempts = 0
    let lastError = null
    if (pdfOnly) {
      const pdfCapture = await capturePdfFallback(record.source.url, timeoutMs)
      markdown = pdfCapture.markdown
      sourceDocumentHash = pdfCapture.sourceDocumentHash
      pageCount = pdfCapture.pageCount
      responseContentType = pdfCapture.responseContentType
      captureMethod = 'manual_official_pdf_text'
      attempts = 1
    } else if (httpOnly || !firecrawlKey) {
      markdown = await captureHtmlFallback(record.source.url, timeoutMs)
      captureMethod = 'http_html_fallback'
      attempts = 1
    } else {
      for (let attempt = 1; attempt <= maxAttempts; attempt += 1) {
        attempts = attempt
        try {
          const response = await fetch('https://api.firecrawl.dev/v1/scrape', {
            method: 'POST',
            headers: { Authorization: `Bearer ${firecrawlKey}`, 'Content-Type': 'application/json' },
            body: JSON.stringify({
              url: record.source.url,
              formats: ['markdown'],
              onlyMainContent: true,
              timeout: timeoutMs,
            }),
            signal: AbortSignal.timeout(timeoutMs + 15000),
          })
          const payload = await response.json().catch(() => ({}))
          markdown = payload?.data?.markdown
          if (!response.ok || !payload?.success || typeof markdown !== 'string' || !isUsableMarkdown(markdown)) {
            throw new Error(`Firecrawl returned ${response.status}: ${payload?.error ?? 'no usable markdown content'}`)
          }
          lastError = null
          break
        } catch (error) {
          lastError = error
          const failure = failureMetadata(error)
          if (!failure.retryable || attempt === maxAttempts) break
          await wait(retryDelayMs(attempt))
        }
      }
      if (lastError && allowHttpFallback) {
        const firecrawlError = lastError
        try {
          markdown = await captureHtmlFallback(record.source.url, timeoutMs)
          captureMethod = 'http_html_fallback'
          attempts += 1
          lastError = null
        } catch (fallbackError) {
          const firecrawlMessage = firecrawlError instanceof Error ? firecrawlError.message : String(firecrawlError)
          const fallbackMessage = fallbackError instanceof Error ? fallbackError.message : String(fallbackError)
          lastError = new Error(`Firecrawl capture failed after ${attempts} attempt(s): ${firecrawlMessage}; HTTP fallback failed: ${fallbackMessage}`)
          lastError.attempts = attempts
        }
      }
    }
    if (lastError || typeof markdown !== 'string') {
      throw errorWithAttempts(lastError ?? new Error('Firecrawl returned no usable markdown content'), attempts)
    }
    const contentHash = createHash('sha256').update(markdown).digest('hex')
    const relativePath = path.join('.catalog-snapshots', runId, snapshotFileName(record.slug, contentHash)).replaceAll('\\', '/')
    if (process.argv.includes('--write')) {
      fs.mkdirSync(runDirectory, { recursive: true })
      fs.writeFileSync(path.join(root, relativePath), markdown, 'utf8')
    }
    captures.push({
      slug: record.slug,
      name: record.name,
      sourceUrl: record.source.url,
      sourceAnchor: record.source.anchor,
      fetchedAt: startedAt,
      status: 'captured',
      captureRole: 'primary',
      contentHash,
      characterCount: markdown.length,
      attempts,
      captureMethod,
      sourceDocumentHash,
      pageCount,
      responseContentType,
      snapshotPath: process.argv.includes('--write') ? relativePath : null,
      reviewStatus: 'in_review',
      publicationStatus: 'blocked',
    })
  } catch (error) {
    const failure = failureMetadata(error)
    captures.push({
      slug: record.slug,
      name: record.name,
      sourceUrl: record.source.url,
      sourceAnchor: record.source.anchor,
      fetchedAt: startedAt,
      status: 'failed',
      error: failure.error,
      failureKind: failure.failureKind,
      retryable: failure.retryable,
      attempts: Number(error?.attempts ?? 1),
      reviewStatus: 'in_review',
      publicationStatus: 'blocked',
    })
  }
}

const output = {
  schemaVersion: 1,
  generatedAt: new Date().toISOString(),
  status: 'local_evidence_capture',
  interpretation: 'This manifest records live official-source fetches for editorial review. A captured snapshot is not a publication approval or an eligibility decision.',
  summary: {
    requested: selected.length,
    captured: captures.filter(capture => capture.status === 'captured').length,
    failed: captures.filter(capture => capture.status === 'failed').length,
    publicationReady: 0,
  },
  captures,
}

if (process.argv.includes('--write')) {
  const append = !process.argv.includes('--replace') && existingManifest?.captures
  const capturesByKey = new Map((append ? existingManifest.captures : []).map(capture => [captureKey(capture), capture]))
  for (const capture of captures) capturesByKey.set(captureKey(capture), capture)
  const mergedCaptures = [...capturesByKey.values()].sort((a, b) => captureKey(a).localeCompare(captureKey(b)))
  output.captures = mergedCaptures
  output.summary = {
    requested: selected.length,
    captured: mergedCaptures.filter(capture => capture.status === 'captured').length,
    failed: mergedCaptures.filter(capture => capture.status === 'failed').length,
    publicationReady: 0,
  }
  fs.writeFileSync(outputPath, `${JSON.stringify(output, null, 2)}\n`, 'utf8')
}
console.log(JSON.stringify(output.summary, null, 2))
if (output.summary.failed > 0) {
  console.error(JSON.stringify(captures.filter(capture => capture.status === 'failed'), null, 2))
  process.exitCode = 1
}
