// Writes the catalog snapshot the results-engine tests run against, so the
// persona checks use real records without needing a database.
//
//   node scripts/mvp-export-engine-snapshot.mjs
//
// Records and relationships come from the linked Supabase project (public data
// only). Pack tags, rates, mappings and facts come from supabase/seed/mvp/, the
// reviewed source of those tables.
import { execSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const read = name => JSON.parse(fs.readFileSync(path.join(root, 'supabase/seed/mvp', name), 'utf8'))
const out = path.join(root, 'src/lib/opportunities/engine/__tests__/catalog-snapshot.json')

function query(sql) {
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'engine-snapshot-')), 'query.sql')
  fs.writeFileSync(file, sql)
  const stdout = execSync(`npx --yes supabase@2.117.0 db query --linked --file "${file}"`, {
    cwd: root, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'], shell: true,
  })
  return JSON.parse(stdout.slice(stdout.indexOf('{'))).rows
}

const records = query(`
  select o.id, o.slug, v.title, o.opportunity_type, o.status, o.geography, v.id as version_id, r.rules,
    v.application->>'route' as apply_route, v.benefit_summary->>'headline' as benefit_headline,
    coalesce(to_jsonb(o) ->> 'last_checked_at', v.last_verified_at::text) as last_checked_at,
    coalesce((select json_agg(json_build_object('windowType', w.window_type, 'opensAt', w.opens_at, 'closesAt', w.closes_at) order by w.window_type, w.opens_at)
       from public.opportunity_windows w where w.opportunity_version_id = v.id), '[]'::json) as windows,
    (select count(*) from public.opportunity_requirements q where q.opportunity_version_id = v.id) as required_count,
    (select count(*) from public.opportunity_steps s where s.opportunity_version_id = v.id) as step_count
  from public.opportunities o
  join public.opportunity_versions v on v.id = o.current_version_id and v.review_status = 'approved'
  join public.eligibility_rule_sets r on r.opportunity_version_id = v.id and r.reviewed
  where o.status in ('active', 'upcoming', 'paused', 'pending_renewal', 'closed')
  order by o.slug
`)

const relationships = query(`
  select opportunity_a as a, opportunity_b as b, relation, cap_rule, note_en, source_url
  from public.scheme_relationships order by opportunity_a, opportunity_b, relation
`)

const tags = read('opportunity-packs.json')
const rates = read('benefit-rates.json')
const { states, facts } = read('facts.json')

const snapshot = {
  _note: 'Generated by scripts/mvp-export-engine-snapshot.mjs. Do not edit by hand.',
  records: records.map(record => ({
    id: record.id,
    slug: record.slug,
    title: record.title,
    type: record.opportunity_type,
    status: record.status,
    versionId: record.version_id,
    rules: record.rules,
    windows: record.windows,
    lastCheckedAt: record.last_checked_at,
    packIds: tags[record.slug] ?? [],
    coverage: record.geography?.coverage ?? 'central',
    locations: record.geography?.locations ?? [],
    requiredCount: Number(record.required_count),
    stepCount: Number(record.step_count),
    // As written; the tests run them through the same filter as production.
    applyRoute: record.apply_route ?? null,
    benefitHeadline: record.benefit_headline ?? null,
    rateRows: rates.filter(row => row.slug === record.slug),
  })),
  relationships: relationships.map(row => ({
    a: row.a, b: row.b, relation: row.relation, capRule: row.cap_rule ?? null, noteEn: row.note_en ?? null, sourceUrl: row.source_url,
  })),
  mappings: read('rule-field-map.json'),
  definitions: facts.map(fact => ({
    key: fact.key,
    type: fact.type,
    fixable: fact.fixable,
    ...(fact.values ? { values: (fact.values === '$states' ? states : fact.values).map(value => value[0]) } : {}),
  })),
  activityPacks: Object.fromEntries(read('activities.json').map(activity => [activity.id, activity.packs])),
}

fs.writeFileSync(out, `${JSON.stringify(snapshot, null, 1)}\n`)
console.log(`Wrote ${path.relative(root, out)}: ${snapshot.records.length} records, ${snapshot.relationships.length} relationships.`)
