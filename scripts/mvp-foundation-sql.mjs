// Validates supabase/seed/mvp/*.json (packs, activities, facts) and writes an
// idempotent SQL migration that upserts them.
//
//   node scripts/mvp-foundation-sql.mjs supabase/migrations/<timestamp>_mvp_foundation_seed.sql
//
// Applied migrations are never edited: after changing the JSON, generate a
// new migration file with a new timestamp.
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const read = name => JSON.parse(fs.readFileSync(path.join(root, 'supabase/seed/mvp', name), 'utf8'))
const packs = read('packs.json')
const activities = read('activities.json')
const { states, facts } = read('facts.json')

const errors = []
const ID = /^[a-z][a-z0-9_]*$/
const unique = (list, label) => {
  const seen = new Set()
  for (const id of list) { if (seen.has(id)) errors.push(`duplicate ${label}: ${id}`); seen.add(id) }
}
const filled = (row, keys, label) => keys.forEach(key => { if (typeof row[key] !== 'string' || !row[key].trim()) errors.push(`${label}: missing ${key}`) })

unique(packs.map(p => p.id), 'pack')
const packIds = new Set(packs.map(p => p.id))
for (const p of packs) { if (!ID.test(p.id)) errors.push(`bad pack id ${p.id}`); filled(p, ['name_en', 'name_hi', 'name_mr', 'description_en'], `pack ${p.id}`) }

unique(activities.map(a => a.id), 'activity')
for (const a of activities) {
  const label = `activity ${a.id}`
  if (!ID.test(a.id)) errors.push(`bad ${label}`)
  filled(a, ['en', 'hi', 'mr'], label)
  if (!a.packs?.length) errors.push(`${label}: no pack`)
  for (const p of a.packs ?? []) if (!packIds.has(p)) errors.push(`${label}: unknown pack ${p}`)
  if (!a.nic?.length || a.nic.some(c => !/^\d{4}$/.test(c))) errors.push(`${label}: bad NIC classes ${a.nic}`)
  for (const s of a.sub ?? []) {
    if (!/^\d{5}$/.test(s)) errors.push(`${label}: bad NIC sub-class ${s}`)
    else if (!a.nic.includes(s.slice(0, 4))) errors.push(`${label}: sub-class ${s} is not under its classes ${a.nic}`)
  }
}
for (const p of packIds) if (!activities.some(a => a.packs.includes(p))) errors.push(`pack ${p} has no activities`)

unique(facts.map(f => f.key), 'fact')
const TYPES = new Set(['boolean', 'enum', 'multi_enum', 'number', 'band', 'date', 'text', 'activity_list'])
const valuesFor = f => (f.values === '$states' ? states : f.values)
for (const f of facts) {
  const label = `fact ${f.key}`
  if (!ID.test(f.key)) errors.push(`bad ${label}`)
  if (!TYPES.has(f.type)) errors.push(`${label}: bad type ${f.type}`)
  filled(f, ['en', 'hi', 'mr'], label)
  if (typeof f.fixable !== 'boolean') errors.push(`${label}: fixable must be true/false`)
  if (!(f.stage >= 1 && f.stage <= 9)) errors.push(`${label}: bad stage`)
  for (const p of f.packs ?? []) if (!packIds.has(p)) errors.push(`${label}: unknown pack ${p}`)
  const values = valuesFor(f)
  const needsValues = ['enum', 'multi_enum', 'band'].includes(f.type)
  if (needsValues !== Boolean(values)) errors.push(`${label}: values ${needsValues ? 'missing' : 'not allowed'}`)
  if (values) {
    unique(values.map(v => v[0]), `${label} value`)
    for (const v of values) if (v.length !== 4 || !ID.test(v[0]) && !/^[0-9a-z_]+$/.test(v[0]) || v.slice(1).some(t => !t?.trim())) errors.push(`${label}: bad value ${JSON.stringify(v)}`)
  }
  if (f.sensitive && !f.why) errors.push(`${label}: sensitive facts must say why they are asked`)
}

if (errors.length) {
  console.error(`Foundation data has ${errors.length} problem(s):\n- ${errors.join('\n- ')}`)
  process.exit(1)
}

const out = process.argv[2]
const q = value => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`)
const arr = list => (list?.length ? `array[${list.map(q).join(', ')}]::text[]` : `'{}'::text[]`)
const json = value => (value === null || value === undefined ? 'null' : `${q(JSON.stringify(value))}::jsonb`)

const sql = [
  `-- Generated by scripts/mvp-foundation-sql.mjs from supabase/seed/mvp/*.json.`,
  `-- ${packs.length} packs, ${activities.length} activities, ${facts.length} facts. Do not edit by hand.`,
  '',
  'insert into public.packs (id, sort_order, name_en, name_hi, name_mr, description_en, is_lite) values',
  packs.map(p => `  (${q(p.id)}, ${p.sort_order}, ${q(p.name_en)}, ${q(p.name_hi)}, ${q(p.name_mr)}, ${q(p.description_en)}, ${p.is_lite})`).join(',\n'),
  'on conflict (id) do update set sort_order = excluded.sort_order, name_en = excluded.name_en, name_hi = excluded.name_hi, name_mr = excluded.name_mr, description_en = excluded.description_en, is_lite = excluded.is_lite;',
  '',
  'insert into public.activities (id, sort_order, label_en, label_hi, label_mr, synonyms, nic2008_classes, nic2008_subclasses, icon) values',
  activities.map((a, i) => `  (${q(a.id)}, ${i + 1}, ${q(a.en)}, ${q(a.hi)}, ${q(a.mr)}, ${arr(a.synonyms)}, ${arr(a.nic)}, ${arr(a.sub)}, ${q(a.icon ?? null)})`).join(',\n'),
  'on conflict (id) do update set sort_order = excluded.sort_order, label_en = excluded.label_en, label_hi = excluded.label_hi, label_mr = excluded.label_mr, synonyms = excluded.synonyms, nic2008_classes = excluded.nic2008_classes, nic2008_subclasses = excluded.nic2008_subclasses, icon = excluded.icon;',
  '',
  `delete from public.activity_packs where activity_id in (${activities.map(a => q(a.id)).join(', ')});`,
  'insert into public.activity_packs (activity_id, pack_id) values',
  activities.flatMap(a => a.packs.map(p => `  (${q(a.id)}, ${q(p)})`)).join(',\n') + ';',
  '',
  'insert into public.fact_definitions (key, value_type, allowed_values, unit, fixable, sensitive, ask_stage, pack_ids, label_en, label_hi, label_mr, why_en) values',
  facts.map(f => {
    const values = valuesFor(f)?.map(([value, en, hi, mr]) => ({ value, label_en: en, label_hi: hi, label_mr: mr })) ?? null
    return `  (${q(f.key)}, ${q(f.type)}, ${json(values)}, ${q(f.unit ?? null)}, ${f.fixable}, ${Boolean(f.sensitive)}, ${f.stage}, ${arr(f.packs)}, ${q(f.en)}, ${q(f.hi)}, ${q(f.mr)}, ${q(f.why ?? null)})`
  }).join(',\n'),
  'on conflict (key) do update set value_type = excluded.value_type, allowed_values = excluded.allowed_values, unit = excluded.unit, fixable = excluded.fixable, sensitive = excluded.sensitive, ask_stage = excluded.ask_stage, pack_ids = excluded.pack_ids, label_en = excluded.label_en, label_hi = excluded.label_hi, label_mr = excluded.label_mr, why_en = excluded.why_en;',
  '',
].join('\n')

if (out) {
  fs.writeFileSync(path.resolve(out), sql)
  console.log(`Wrote ${out}: ${packs.length} packs, ${activities.length} activities, ${facts.length} facts.`)
} else {
  console.log(`Valid: ${packs.length} packs, ${activities.length} activities, ${facts.length} facts. Pass an output path to write SQL.`)
}
