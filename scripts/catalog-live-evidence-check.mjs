import fs from 'node:fs'
import path from 'node:path'
import { createHash } from 'node:crypto'

const root = process.cwd()
const capturePath = path.join(root, 'docs', 'catalog-live-source-capture.json')
const outputPath = path.join(root, 'docs', 'catalog-live-evidence-integrity.json')

function normalize(value) {
  return String(value ?? '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').replace(/\s+/g, ' ').trim()
}

function meaningfulTokens(value) {
  return normalize(value).split(' ').filter(token => token.length >= 4 && !['pages', 'page', 'section', 'source', 'official', 'criteria', 'terms'].includes(token))
}

function isUsableSnapshotBody(body) {
  const normalized = body.trim().toLowerCase()
  if (normalized.length < 20) return false
  if (/^(?:#\s*)?(?:not found|page not found|\d{3}\s+error)(?:\s|$)/.test(normalized)) return false
  if (normalized.includes('page not found')) return false
  if (normalized.includes('requested page could not be found')) return false
  if (normalized.includes('requested url was rejected')) return false
  if (normalized.includes('consult with your administrator')) return false
  if (normalized.includes('access denied')) return false
  if (normalized.includes('potentially suspicious content entered by you')) return false
  if (normalized.includes('review all errors and resolve them one by one')) return false
  if (normalized.includes('support id:')) return false
  if (normalized.includes('404 banner')) return false
  if (normalized.includes('request blocked')) return false
  if (normalized.includes("we can't connect to the server at this time")) return false
  if (normalized.includes('generated by cloudfront')) return false
  return true
}

if (!fs.existsSync(capturePath)) {
  console.log('catalog live evidence check skipped: no capture manifest exists yet')
  process.exit(0)
}

const capture = JSON.parse(fs.readFileSync(capturePath, 'utf8'))
const records = capture.captures.filter(item => item.status === 'captured').map(item => {
  const absolutePath = path.join(root, item.snapshotPath)
  const exists = fs.existsSync(absolutePath)
  const body = exists ? fs.readFileSync(absolutePath, 'utf8') : ''
  const actualHash = createHash('sha256').update(body).digest('hex')
  const normalizedBody = normalize(body)
  const phrases = String(item.sourceAnchor ?? '').split(';').map(value => value.trim()).filter(Boolean)
  const anchorMatches = phrases.map(phrase => {
    const tokens = meaningfulTokens(phrase)
    const matchedTokens = tokens.filter(token => normalizedBody.includes(token))
    return { phrase, matchedTokens, matched: matchedTokens.length >= Math.min(3, Math.max(1, tokens.length)) }
  })
  const integrityPassed = exists
    && isUsableSnapshotBody(body)
    && actualHash === item.contentHash
    && anchorMatches.some(match => match.matched)
  return {
    slug: item.slug,
    sourceUrl: item.sourceUrl,
    snapshotPath: item.snapshotPath,
    snapshotExists: exists,
    expectedHash: item.contentHash,
    actualHash,
    characterCount: body.length,
    anchorMatches,
    integrityStatus: integrityPassed ? 'passed' : 'needs_review',
    publicationStatus: 'blocked',
  }
})

const output = {
  schemaVersion: 1,
  generatedAt: new Date().toISOString(),
  status: 'local_evidence_integrity',
  interpretation: 'This check proves local snapshot integrity and anchor presence only. It does not prove factual accuracy, eligibility, current status, or publication approval.',
  summary: {
    capturedSnapshots: records.length,
    integrityPassed: records.filter(record => record.integrityStatus === 'passed').length,
    needsReview: records.filter(record => record.integrityStatus !== 'passed').length,
    publicationReady: 0,
  },
  records,
}

if (process.argv.includes('--write')) fs.writeFileSync(outputPath, `${JSON.stringify(output, null, 2)}\n`, 'utf8')
console.log(JSON.stringify(output.summary, null, 2))
if (output.summary.needsReview > 0) process.exitCode = 1
