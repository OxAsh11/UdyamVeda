// Validates supabase/seed/mvp/opportunity-packs.json and benefit-rates.json and
// writes an idempotent SQL migration that replaces the pack tags and the rates
// on each record's current version. The migration fails if a slug is unknown.
//
//   node scripts/mvp-engine-sql.mjs supabase/migrations/<timestamp>_results_engine_seed.sql
//
// Applied migrations are never edited: after changing the JSON, generate a
// new migration file with a new timestamp.
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const read = name => JSON.parse(fs.readFileSync(path.join(root, 'supabase/seed/mvp', name), 'utf8'))
const tags = read('opportunity-packs.json')
const rates = read('benefit-rates.json')
const packIds = new Set(read('packs.json').map(pack => pack.id))
const factKeys = new Set(read('facts.json').facts.map(fact => fact.key))

function fieldsIn(node) {
  if (!node || typeof node !== 'object') return []
  if (Array.isArray(node.all)) return node.all.flatMap(fieldsIn)
  if (Array.isArray(node.any)) return node.any.flatMap(fieldsIn)
  return typeof node.field === 'string' ? [node.field] : []
}

const errors = []
for (const [slug, packs] of Object.entries(tags)) {
  for (const pack of packs) if (!packIds.has(pack)) errors.push(`${slug}: unknown pack ${pack}`)
}
for (const row of rates) {
  if (!row.source_url?.startsWith('https://')) errors.push(`${row.slug}: source must be https`)
  if (!row.quote?.trim()) errors.push(`${row.slug}: quote is required`)
  if (!row.label_en?.trim()) errors.push(`${row.slug}: label is required`)
  for (const field of fieldsIn(row.applies_when)) if (!factKeys.has(field)) errors.push(`${row.slug}: unknown fact ${field}`)
}
if (errors.length) {
  console.error(`Engine seeds have ${errors.length} problem(s):\n- ${errors.join('\n- ')}`)
  process.exit(1)
}

const q = value => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`)
const n = value => (value === null || value === undefined ? 'null' : String(Number(value)))
const slugs = [...new Set([...Object.keys(tags), ...rates.map(row => row.slug)])]
const rateSlugs = [...new Set(rates.map(row => row.slug))]

const sql = [
  '-- Generated by scripts/mvp-engine-sql.mjs from supabase/seed/mvp/opportunity-packs.json and benefit-rates.json. Do not edit by hand.',
  `-- ${Object.keys(tags).length} records tagged to packs, ${rates.length} benefit-rate rows for ${rateSlugs.length} schemes.`,
  '',
  'do $$',
  'declare',
  '  missing text;',
  'begin',
  '  select string_agg(x.slug, \', \') into missing',
  `  from (values ${slugs.map(slug => `(${q(slug)})`).join(', ')}) as x(slug)`,
  '  where not exists (select 1 from public.opportunities o where o.slug = x.slug and o.current_version_id is not null);',
  '  if missing is not null then',
  "    raise exception 'Unknown catalog records: %', missing;",
  '  end if;',
  'end $$;',
  '',
  'delete from public.opportunity_packs;',
  '',
  'insert into public.opportunity_packs (opportunity_id, pack_id)',
  'select o.id, x.pack_id',
  'from (values',
  Object.entries(tags).flatMap(([slug, packs]) => packs.map(pack => `  (${q(slug)}, ${q(pack)})`)).join(',\n'),
  ') as x(slug, pack_id)',
  'join public.opportunities o on o.slug = x.slug;',
  '',
  'delete from public.benefit_rates',
  `where opportunity_version_id in (select current_version_id from public.opportunities where slug in (${rateSlugs.map(q).join(', ')}));`,
  '',
  'insert into public.benefit_rates (',
  '  opportunity_version_id, priority, applies_when, area, project_types, own_pct, includes_loan, provisional, subsidy_pct,',
  '  subsidy_cap_inr, subsidy_floor_inr, loan_cap_inr, project_min_inr, project_cap_inr,',
  '  interest_rate_pct, interest_subvention_pct, label_en, source_url, quote',
  ')',
  'select',
  '  o.current_version_id, x.priority::smallint, x.applies_when::jsonb, x.area, x.project_types::text[], x.own_pct::numeric, x.includes_loan, x.provisional, x.subsidy_pct::numeric,',
  '  x.subsidy_cap_inr::numeric, x.subsidy_floor_inr::numeric, x.loan_cap_inr::numeric, x.project_min_inr::numeric, x.project_cap_inr::numeric,',
  '  x.interest_rate_pct::numeric, x.interest_subvention_pct::numeric, x.label_en, x.source_url, x.quote',
  'from (values',
  rates.map(row => `  (${[
    q(row.slug),
    n(row.priority),
    row.applies_when ? q(JSON.stringify(row.applies_when)) : 'null',
    q(row.area),
    q(`{${row.project_types.join(',')}}`),
    n(row.own_pct),
    String(row.includes_loan ?? true),
    String(row.provisional ?? false),
    n(row.subsidy_pct),
    n(row.subsidy_cap_inr),
    n(row.subsidy_floor_inr),
    n(row.loan_cap_inr),
    n(row.project_min_inr),
    n(row.project_cap_inr),
    n(row.interest_rate_pct),
    n(row.interest_subvention_pct),
    q(row.label_en),
    q(row.source_url),
    q(row.quote),
  ].join(', ')})`).join(',\n'),
  ') as x(slug, priority, applies_when, area, project_types, own_pct, includes_loan, provisional, subsidy_pct, subsidy_cap_inr, subsidy_floor_inr, loan_cap_inr, project_min_inr, project_cap_inr, interest_rate_pct, interest_subvention_pct, label_en, source_url, quote)',
  'join public.opportunities o on o.slug = x.slug;',
  '',
].join('\n')

fs.writeFileSync(path.resolve(process.argv[2]), sql)
console.log(`Wrote ${process.argv[2]}: ${Object.keys(tags).length} tagged records, ${rates.length} rate rows.`)
