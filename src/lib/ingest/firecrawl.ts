import { isOfficialSourceUrl } from '@/lib/opportunities/editorial'

export interface FirecrawlDocument {
  markdown: string
  metadata: Record<string, unknown>
  captureMethod: 'firecrawl_markdown'
  finalUrl: string
  responseStatus: number
  responseContentType: string | null
}

function isUsableMarkdown(markdown: string) {
  const normalized = markdown.trim().toLowerCase()
  const urlLike = /^(?:https?:\/\/|\/)\S+$/
  if (normalized.length < 80) return false
  if (urlLike.test(normalized)) return false
  if (/^(?:#\s*)?(?:not found|page not found|\d{3}\s+error)(?:\s|$)/.test(normalized)) return false
  if (normalized.includes('the requested url was not found')) return false
  if (normalized.includes('page not found')) return false
  if (normalized.includes('requested page could not be found')) return false
  if (normalized.includes('requested url was rejected')) return false
  if (normalized.includes('consult with your administrator')) return false
  if (normalized.includes('access denied')) return false
  if (normalized.includes('potentially suspicious content entered by you')) return false
  if (normalized.includes('review all errors and resolve them one by one')) return false
  if (normalized.includes('support id:')) return false
  if (normalized.includes('404 banner')) return false
  if (normalized.includes('request blocked')) return false
  if (normalized.includes("we can't connect to the server at this time")) return false
  if (normalized.includes('generated by cloudfront')) return false
  if (normalized.includes('error code "err_')) return false
  return true
}

export async function scrapeOfficialSource(url: string): Promise<FirecrawlDocument> {
  const apiKey = process.env.FIRECRAWL_API_KEY
  if (!apiKey) throw new Error('FIRECRAWL_API_KEY is not configured')
  if (!isOfficialSourceUrl(url)) throw new Error('Only registered official Government or allowlisted implementing-agency URLs may be crawled')

  const response = await fetch('https://api.firecrawl.dev/v1/scrape', {
    method: 'POST',
    headers: { Authorization: `Bearer ${apiKey}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ url, formats: ['markdown'], onlyMainContent: true, timeout: 30000 }),
    signal: AbortSignal.timeout(45000),
  })

  const payload = await response.json() as { success?: boolean; data?: FirecrawlDocument; error?: string }
  if (!response.ok) throw new Error(`Firecrawl returned ${response.status}: ${payload.error ?? 'request failed'}`)
  if (!payload.success || !payload.data) throw new Error(payload.error || 'Firecrawl returned no document')
  if (typeof payload.data.markdown !== 'string' || !isUsableMarkdown(payload.data.markdown)) {
    throw new Error('Firecrawl returned no usable markdown content')
  }
  const metadata = payload.data.metadata ?? {}
  const finalUrl = typeof metadata.sourceURL === 'string' && metadata.sourceURL.trim()
    ? metadata.sourceURL.trim()
    : url
  return {
    ...payload.data,
    metadata,
    captureMethod: 'firecrawl_markdown',
    finalUrl,
    responseStatus: response.status,
    responseContentType: response.headers.get('content-type'),
  }
}
